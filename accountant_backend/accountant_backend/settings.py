# Database
# https://docs.djangoproject.com/en/6.0/ref/settings/#databases
#
# SQLite (file-based, single-writer) is fine for local dev and a small early
# launch, but not for real concurrent production traffic long-term. Set
# DATABASE_URL (e.g. postgres://user:pass@host:5432/dbname) to switch to
# Postgres — nothing else in the app depends on the database engine, this is
# a drop-in swap when you're ready to migrate.
# Requires `psycopg[binary]` and `dj-database-url` (see requirements.txt).
#
# Running production on SQLite deliberately, for now (e.g. launching solo
# before a Postgres migration): set DJANGO_ALLOW_SQLITE_IN_PRODUCTION=True to
# acknowledge this and skip the guard below. This is an explicit opt-in, not
# a default, so it stays visible in your env config as a reminder it's
# temporary rather than something that silently slipped through.

_database_url = os.environ.get("DATABASE_URL", "")
_allow_sqlite_in_prod = os.environ.get("DJANGO_ALLOW_SQLITE_IN_PRODUCTION", "False") == "True"
if _database_url:
    import dj_database_url

    DATABASES = {
        'default': dj_database_url.parse(_database_url, conn_max_age=600, ssl_require=not DEBUG)
    }
elif not DEBUG and not _allow_sqlite_in_prod:
    raise ImproperlyConfigured(
        "DATABASE_URL must be set (e.g. postgres://user:pass@host:5432/dbname) when "
        "DJANGO_DEBUG is not 'True'. If you're intentionally running production on SQLite "
        "for now, set DJANGO_ALLOW_SQLITE_IN_PRODUCTION=True instead."
    )
else:
    # NOTE: with DEBUG=False and no DATABASE_URL, this is the
    # DJANGO_ALLOW_SQLITE_IN_PRODUCTION opt-in path — same file-based engine
    # as local dev, just pointed at whatever BASE_DIR resolves to on the
    # production host. Back this file up; SQLite has no built-in replication.
    #
    # A busy timeout matters a lot once this is a real multi-request
    # production server instead of a single dev process: without it,
    # concurrent writes (two sales saved at the same moment, etc.) commonly
    # fail immediately with "database is locked" instead of briefly queuing.
    # WAL journal mode (which allows concurrent readers alongside a writer)
    # is enabled separately via the `connection_created` signal below —
    # SQLite's Django backend has no OPTIONS key for arbitrary PRAGMAs
    # (`init_command` is a MySQL-only option; passing it here would just be
    # silently ignored/error, not actually set WAL mode).
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'db.sqlite3',
            'OPTIONS': {
                'timeout': 20,
            },
        }
    }


