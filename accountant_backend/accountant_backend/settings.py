def _collect_keys(var_name, max_n=10):
    """Reads `var_name` plus `var_name_1`..`var_name_{max_n}` from the
    environment and returns whichever are actually set, in that order —
    used for free-tier key rotation (apps.chat.groq_client /
    apps.image_info_extractor.gemini_client): when one key's quota is
    exhausted, the client tries the next one automatically rather than
    failing the request. Duplicates are dropped. An empty list means
    "not configured" (same meaning the single-key settings used to have)."""
    keys = []
    single = os.environ.get(var_name, "").strip()
    if single:
        keys.append(single)
    for i in range(1, max_n + 1):
        value = os.environ.get(f"{var_name}_{i}", "").strip()
        if value and value not in keys:
            keys.append(value)
    return keys


